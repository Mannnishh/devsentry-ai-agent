"""Provider-agnostic LLM client implementation using Groq."""

from collections.abc import Generator
from typing import Any

from groq import Groq

from src.config import settings


class LLMClient:
    """Wrapper around Groq Cloud LLM inference.

    Supports both standard synchronous text generation and real-time streaming.
    """

    def __init__(self, api_key: str | None = None, default_model: str | None = None):
        # Fall back to our validated settings if not passed explicitly
        self.api_key = api_key or settings.groq_api_key
        self.default_model = default_model or settings.default_model
        self._client = Groq(api_key=self.api_key)

    def generate(
        self,
        messages: list[dict[str, str]],
        model: str | None = None,
        temperature: float | None = None,
        **kwargs: Any,
    ) -> str:
        """Generate a complete text response synchronously (waits for full answer)."""
        selected_model = model or self.default_model
        temp = temperature if temperature is not None else settings.llm_temperature

        response = self._client.chat.completions.create(
            model=selected_model,
            messages=messages,  # type: ignore[arg-type]
            temperature=temp,
            **kwargs,
        )
        return response.choices[0].message.content or ""

    def stream(
        self,
        messages: list[dict[str, str]],
        model: str | None = None,
        temperature: float | None = None,
        **kwargs: Any,
    ) -> Generator[str, None, None]:
        """Stream chunks of tokens in real time as they are generated by the model."""
        selected_model = model or self.default_model
        temp = temperature if temperature is not None else settings.llm_temperature

        stream_response = self._client.chat.completions.create(
            model=selected_model,
            messages=messages,  # type: ignore[arg-type]
            temperature=temp,
            stream=True,
            **kwargs,
        )

        for chunk in stream_response:
            delta = chunk.choices[0].delta.content
            if delta:
                yield delta
